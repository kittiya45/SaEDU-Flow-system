#!/usr/bin/env node
/**
 * รวมไฟล์ SQL จาก supabase/ เป็น dev-sql-bundle.js
 * ให้ปุ่ม "คัดลอก SQL" ใน Dev Panel ทำงานได้โดยไม่ต้อง fetch ไฟล์จากเซิร์ฟเวอร์
 *
 * รายการต้องตรงกับ DEV_MIGRATIONS ใน dev.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SQL_DIR = path.join(ROOT, 'supabase');
const OUT = path.join(ROOT, 'dev-sql-bundle.js');

const FILES = [
  'migration_auth_rls.sql',
  'create_dev_role.sql',
  'create_admin_config_tables.sql',
  'create_announcements.sql',
  'user_signatures.sql',
  'line_notifications.sql',
  'workflow_ops_rpc.sql',
  'overdue_once_auto_approve.sql',
  'scale_hardening.sql',
  'private_storage_bucket.sql',
  'phase2_dev_ops.sql',
  'phase3_dev_users.sql',
  'cron_overdue.sql',
];

const bundle = {};
let missing = 0;
for (const file of FILES) {
  const p = path.join(SQL_DIR, file);
  if (!fs.existsSync(p)) {
    console.warn('bundle-dev-sql: missing', file);
    missing++;
    continue;
  }
  bundle[file] = fs.readFileSync(p, 'utf8');
}

const header =
  '/* AUTO-GENERATED by scripts/bundle-dev-sql.mjs — อย่าแก้มือ รัน npm run build */\n';
fs.writeFileSync(OUT, header + 'var DEV_SQL_BUNDLE=' + JSON.stringify(bundle) + ';\n', 'utf8');
console.log('bundle-dev-sql: wrote', OUT, Object.keys(bundle).length, 'files' + (missing ? ` (${missing} missing)` : ''));
